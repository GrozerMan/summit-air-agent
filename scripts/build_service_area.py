"""Build config/service_area.csv from GeoNames' US postal-code file.

    curl -sSfLO https://download.geonames.org/export/zip/US.zip && unzip US.zip
    uv run python -I scripts/build_service_area.py path/to/US.txt

Keeps every ZIP in the counties Summit Air serves, with GeoNames' place name. Data:
GeoNames (https://www.geonames.org), CC BY 4.0. Re-run when the service area changes;
the agent itself only reads the CSV.
"""

import csv
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main(geonames_path: str) -> None:
    with open(ROOT / "config" / "business.toml", "rb") as f:
        counties = set(tomllib.load(f)["service_area"]["counties"])

    rows = set()
    with open(geonames_path, encoding="utf-8") as f:
        for line in f:
            cols = line.rstrip("\n").split("\t")
            if len(cols) < 6:
                continue
            zip_code, place, state, county = cols[1], cols[2], cols[4], cols[5]
            if state == "NY" and county in counties and len(zip_code) == 5 and zip_code.isdigit():
                rows.add((zip_code, place, county))

    found = {county for _, _, county in rows}
    if missing := counties - found:
        sys.exit(f"no ZIPs found for {sorted(missing)}; check the county names in business.toml")

    out = ROOT / "config" / "service_area.csv"
    with open(out, "w", newline="", encoding="utf-8") as f:
        f.write("# Generated by scripts/build_service_area.py from GeoNames (CC BY 4.0). Don't edit by hand.\n")
        writer = csv.writer(f)
        writer.writerow(["zip", "place", "county"])
        writer.writerows(sorted(rows))
    print(f"wrote {len(rows)} ZIPs across {len(found)} counties to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
